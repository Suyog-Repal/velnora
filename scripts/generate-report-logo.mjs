// Regenerates src/services/reportLogo.ts from the app's own logo asset (assets/android-icon-foreground.png).
// The PDF is built from an HTML string, which needs the logo inline; a test fails if this file drifts from the asset.
import { readFileSync, writeFileSync } from 'node:fs';
const png = readFileSync(new URL('../assets/android-icon-foreground.png', import.meta.url));
const out = `// GENERATED by scripts/generate-report-logo.mjs from assets/android-icon-foreground.png. Do not edit by hand.
export const REPORT_LOGO_PNG_BASE64 = '${png.toString('base64')}';
`;
writeFileSync(new URL('../src/services/reportLogo.ts', import.meta.url), out);
console.log('wrote src/services/reportLogo.ts', png.length, 'bytes');
